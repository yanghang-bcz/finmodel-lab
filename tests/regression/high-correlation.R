}else message(selected$error)
# AIC* = n*log(RSS/n)+2*rank matches extractAIC(lm) with unknown scale.
# AIC(logLik) adds n*(1+log(2*pi))+2; same ordering on identical rows.
# Accept only improvement >1e-7; ties by source-column index, then action.
# Greedy search is not exhaustive. Selected-model p-values ignore selection bias.

lambdas <- 10^seq(-6,0,length.out=31)
