cv_lasso <- tryCatch(rcv(Xtr,ytr,lambdas,"lasso",tol,maxit),error=function(e)list(error=conditionMessage(e)))
mode <- "cv"; method <- "ridge"; manual_lambda <- 0.001
fit_safe <- function(type,cv){tryCatch({if(!(mode=="manual"&&"compare"=="regularization")&&!is.null(cv$error))stop(cv$error);rfit(Xtr,ytr,if(mode=="manual"&&"compare"=="regularization")manual_lambda else cv$lambda,type,tol,maxit)},error=function(e)list(error=conditionMessage(e)))}
ridge <- fit_safe("ridge",cv_ridge);lasso <- fit_safe("lasso",cv_lasso)
for(q in list(ridge,lasso))if(is.null(q$error)){print(q[c("coef","standardCoef","lambda","iter","kkt","edf","nonzero")]);print(rmetric(yte,rpredict(q,Xte)))}else message(q$error)
print(cv_ridge);print(cv_lasso)
manual_cv_ridge <- tryCatch(rcv(Xtr,ytr,manual_lambda,"ridge",tol,maxit),error=function(e)list(error=conditionMessage(e)))
manual_cv_lasso <- tryCatch(rcv(Xtr,ytr,manual_lambda,"lasso",tol,maxit),error=function(e)list(error=conditionMessage(e)))
print(manual_cv_ridge);print(manual_cv_lasso)
# J=RSS/(2*n)+lambda/2*sum(b^2) for Ridge; +lambda*sum(abs(b)) for Lasso.
# b refers to centered training-RMS-standardized X; y stays in return decimals.
# Do not assume glmnet Ridge lambda matches without checking its y scaling.
# Zero-count reporting threshold: |standardized coefficient|>1e-10.
# Test is final evaluation, not a tuning criterion. Repeated exploration weakens independence.

evaluate <- function(name,train_pred,test_pred,complexity){c(Model=name,Train_RMSE=sqrt(mean((ytr-train_pred)^2)),rmetric(yte,test_pred),Complexity=complexity)}
